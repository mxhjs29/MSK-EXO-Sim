"""Configure the optional GMR backend with project-owned model parameters."""

import sys


def prepare_gmr_backend():
    """Install parameters before GMR imports its solver and viewer modules.

    The solver implementation and non-MSK robot configurations come from the
    pinned GMR package. Its myofullbody target is generated by myo_sim, and the
    retargeting pipeline can then specialize that target for its Assist view.
    """
    from . import gmr_params

    sys.modules["general_motion_retargeting.params"] = gmr_params
    backend = sys.modules.get("general_motion_retargeting")
    if backend is not None:
        for name in (
            "IK_CONFIG_ROOT",
            "ASSET_ROOT",
            "ROBOT_XML_DICT",
            "IK_CONFIG_DICT",
            "ROBOT_BASE_DICT",
            "VIEWER_CAM_DISTANCE_DICT",
        ):
            setattr(backend, name, getattr(gmr_params, name))
